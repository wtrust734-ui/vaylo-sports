const SPORTS = ["football", "basketball", "rugby", "athletics", "swimming", "tennis", "cricket", "cycling", "boxing", "volleyball", "hockey", "multisport"];
const fmtFromTheme = (t) =>
  /-VIDEO$/.test(t) ? "video" :
  /-IMAGE$/.test(t) ? "image" :
  /-CAROUSEL$/.test(t) ? "carousel" :
  /-REPORT$/.test(t) ? "report" :
  "image";
const sportFromTheme = (t) => {
  for (const s of ["football", "basketball", "rugby", "swimming", "tennis", "cricket", "cycling", "boxing", "volleyball", "hockey", "athletics"]) {
    if (t.toLowerCase().includes(s)) return s;
  }
  return "multisport";
};
const dowOf = (iso) => ["sun","mon","tue","wed","thu","fri","sat"][new Date(iso + "T12:00:00Z").getUTCDay()];

const start = new Date("2026-10-18");
const end = new Date("2027-06-30");
let rows = [];
for (let d = new Date(start); d <= end; d.setUTCDate(d.getUTCDate() + 1)) {
  const iso = d.toISOString().slice(0, 10);
  const theme = THEMES[iso];
  if (!theme) throw new Error("no theme for " + iso);
  const type = fmtFromTheme(theme);
  const sport = sportFromTheme(theme);
  const dow = dowOf(iso);
  const ymd = iso.replace(/-/g, "");
  const assetName = `VAYLO-${ymd}-${type.toUpperCase()}-${sport.toUpperCase()}-${theme}-V01`;
  // Weekday production schedule from Part 3 (UK local):
  const sched = {
    mon: { start: "09:00", deadline: "15:00", publish: "18:30" },
    tue: { start: "09:00", deadline: "15:00", publish: "12:30" },
    wed: { start: "09:00", deadline: "15:00", publish: "18:30" },
    thu: { start: "09:00", deadline: "15:00", publish: "12:30" },
    fri: { start: "09:00", deadline: "15:00", publish: "18:30" },
    sat: { start: "10:00", deadline: "13:00", publish: "13:00" },
    sun: { start: "10:00", deadline: "13:00", publish: "17:00" },
  }[dow];
  const objective =
    /CONVERSION|CTA|REGISTRATION|ACQUISITION/.test(theme) ? "conversion" :
    /REPORT/.test(theme) ? "campaign-report" :
    /PRODUCT|APP-|FEATURE|WALKTHROUGH|WORKFLOW|ONBOARDING|DEMO/.test(theme) ? "product-demo" :
    /EDUCATION|LEARNING|CAROUSEL|TRAINING-|SPORTS-/.test(theme) ? "education" :
    /BRAND|MISSION|TRUST|LEGACY|HOLIDAY|EVERGREEN/.test(theme) ? "brand-building" :
    "awareness";
  const concept = theme.replace(/-/g, " ").toLowerCase();
  rows.push({ iso, dow, theme, assetName, type, sport, objective, concept, ...sched });
}

const esc = (s) => (s == null ? "null" : `'${String(s).replace(/'/g, "''")}'`);
const lines = rows.map((r) =>
  `('${r.iso}','${r.dow}',${esc(r.theme)},${esc(r.assetName)},'${r.type}',${esc(r.sport)},'athletes 18-30',${esc(r.objective)},${esc(r.concept)},'${r.start}','${r.deadline}',${r.publish ? `'${r.publish}'` : "null"})`
);
const sql = `-- Auto-generated: full Vaylo campaign calendar 2026-10-18 → 2027-06-30 (${rows.length} days).
-- Source: master plan Part 4 themes + Part 3 weekday times. Upsert-safe.
insert into public.ad_engine_calendar
  (day, dow, theme, asset_name, asset_format, sport, audience, objective, concept, produce_start, produce_deadline, publish_time)
values
${lines.join(",\n")}
on conflict (day) do update set
  theme = excluded.theme, asset_name = excluded.asset_name, asset_format = excluded.asset_format,
  sport = excluded.sport, audience = excluded.audience, objective = excluded.objective,
  concept = excluded.concept, produce_start = excluded.produce_start,
  produce_deadline = excluded.produce_deadline, publish_time = excluded.publish_time,
  updated_at = now();
`;
fs.writeFileSync("supabase/migrations/.tmp-calendar.sql", sql);
