// Generates the server-side Event Pack catalog from the client catalog.
//
// Why: `claim_event_pack` used to trust the browser for both the price and the
// right to claim — it stored `pack.priceCents` as sent by the app and granted
// ownership with no payment step — and `public.event_packs` was empty, so the
// server had no price list to check against. Every pack ($12.99–$59.99) was
// free. Prices must live on the server; this script is the bridge.
//
// Run after editing src/config/eventPacks.ts, then apply the emitted migration:
//
//   node scripts/gen-event-packs-sql.cjs
//
// The bundled catalog is evaluated in-process rather than parsed with regexes,
// because the packs are generated from TEMPLATES + per-sport overrides and a
// line-based read would silently miss entries.
// esbuild is required rather than declared: it ships as a hard dependency of
// vite, which this project already builds with, so the module always resolves.
const fs = require("fs");
const path = require("path");
const esbuild = require("esbuild");

const root = path.resolve(__dirname, "..");
const entry = path.join(root, "src", "config", "eventPacks.ts");
const target = path.join(
  root,
  "supabase",
  "migrations",
  "20260927150000_event_pack_server_catalog.sql"
);

const bundled = esbuild.buildSync({
  entryPoints: [entry],
  bundle: true,
  format: "cjs",
  platform: "node",
  write: false,
});

const mod = { exports: {} };
new Function("module", "exports", bundled.outputFiles[0].text)(mod, mod.exports);

const packs = mod.exports.BUILT_IN_EVENT_PACKS;
if (!Array.isArray(packs) || packs.length === 0) {
  throw new Error("BUILT_IN_EVENT_PACKS came back empty — did the export move?");
}

const lit = (value) => (value === null || value === undefined ? "null" : `'${String(value).replace(/'/g, "''")}'`);
const arr = (values) =>
  Array.isArray(values) && values.length
    ? `array[${values.map(lit).join(", ")}]::text[]`
    : "'{}'::text[]";
const num = (value) => (Number.isFinite(Number(value)) ? String(Number(value)) : "0");

const rows = [...packs]
  .sort((a, b) => a.id.localeCompare(b.id))
  .map(
    (p) =>
      "  (" +
      [
        lit(p.id),
        lit(p.name),
        lit(p.sport),
        lit(p.category),
        lit(p.targetEvent ?? p.target_event ?? null),
        lit(p.description),
        num(p.weeks),
        num(p.priceCents),
        lit(p.difficulty),
        lit(p.designedFor ?? null),
        arr(p.includes),
        lit(p.version),
        p.futureUpdatesIncluded ? "true" : "false",
        p.featured ? "true" : "false",
        arr(p.sections),
        num(p.popularity),
        p.retired ? "true" : "false",
      ].join(", ") +
      ")"
  );

const sql = `-- Event Pack catalog — server-side prices.
--
-- GENERATED by scripts/gen-event-packs-sql.cjs from src/config/eventPacks.ts.
-- Do not hand-edit: change the client catalog and re-run the generator.
--
-- Context: the table shipped empty, so \`loadEventPacks()\` fell back entirely to
-- the bundled catalog and \`claim_event_pack\` accepted \`p_price_cents\` from the
-- caller. Ownership was granted with no payment step, which made every pack
-- free and made the recorded price meaningless. Seeding the rows below gives
-- the database the authoritative price the claim function now enforces, and the
-- ON CONFLICT branch means re-running the generator is how admin price edits
-- from src/config/eventPacks.ts reach the server.

insert into public.event_packs (
  pack_id, name, sport, category, target_event, description, weeks, price_cents,
  difficulty, designed_for, includes, version, future_updates_included,
  featured, sections, popularity, retired
) values
${rows.join(",\n")}
on conflict (pack_id) do update set
  name = excluded.name,
  sport = excluded.sport,
  category = excluded.category,
  target_event = excluded.target_event,
  description = excluded.description,
  weeks = excluded.weeks,
  price_cents = excluded.price_cents,
  difficulty = excluded.difficulty,
  designed_for = excluded.designed_for,
  includes = excluded.includes,
  version = excluded.version,
  future_updates_included = excluded.future_updates_included,
  featured = excluded.featured,
  sections = excluded.sections,
  popularity = excluded.popularity,
  retired = excluded.retired,
  updated_at = now();

-- The caller may no longer name the pack's contents or its price: both are
-- read from the catalog row. A paid pack additionally requires a verified
-- purchase, which only process-purchase (service role) can write.
create or replace function public.claim_event_pack(
  p_pack_id text,
  p_pack_name text default null,
  p_sport text default null,
  p_price_cents integer default 0,
  p_version text default null
)
returns jsonb
language plpgsql
security definer
set search_path to 'public'
as $function$
declare
  v_user uuid := auth.uid();
  v_existing uuid;
  v_pack public.event_packs%rowtype;
  v_paid boolean := false;
begin
  if v_user is null then raise exception 'Not authenticated'; end if;
  if p_pack_id is null or length(p_pack_id) = 0 then raise exception 'Missing pack'; end if;

  select id into v_existing from public.event_pack_ownership
    where user_id = v_user and pack_id = p_pack_id;
  if v_existing is not null then
    return jsonb_build_object('ok', true, 'duplicate', true, 'pack_id', p_pack_id);
  end if;

  -- The catalog, not the caller, decides the pack's identity and price.
  -- p_pack_name / p_sport / p_price_cents / p_version are accepted for wire
  -- compatibility with deployed clients and deliberately ignored.
  select * into v_pack from public.event_packs
    where pack_id = p_pack_id and not coalesce(retired, false);
  if v_pack.id is null then
    raise exception 'Unknown or retired event pack: %', p_pack_id;
  end if;

  if coalesce(v_pack.price_cents, 0) > 0 then
    -- A paid pack needs a verified purchase. process-purchase writes
    -- user_purchases from Play Billing; nothing else may.
    select true into v_paid from public.user_purchases
      where user_id = v_user and product_id = 'event_pack:' || p_pack_id
      limit 1;
    if not coalesce(v_paid, false) then
      raise exception 'Purchase required for this event pack';
    end if;
  end if;

  insert into public.event_pack_ownership
    (user_id, pack_id, pack_name, sport, price_cents, version_at_purchase, source)
  values (
    v_user, v_pack.pack_id, v_pack.name, v_pack.sport,
    coalesce(v_pack.price_cents, 0), v_pack.version,
    case when coalesce(v_pack.price_cents, 0) > 0 then 'purchase' else 'free' end
  );

  return jsonb_build_object(
    'ok', true,
    'duplicate', false,
    'pack_id', v_pack.pack_id,
    'price_cents', coalesce(v_pack.price_cents, 0)
  );
end;
$function$;

-- Claiming is a signed-in action; the public API role must not reach it.
revoke all on function public.claim_event_pack(text, text, text, integer, text) from public, anon;
grant execute on function public.claim_event_pack(text, text, text, integer, text) to authenticated, service_role;
`;

fs.writeFileSync(target, sql, "utf8");
console.log(`wrote ${path.relative(root, target)} — ${packs.length} packs`);
