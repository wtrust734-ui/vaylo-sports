// Generates the server-side avatar price catalog from the client catalog.
//
// Why: `purchase_avatar_item*` RPCs previously trusted the `p_cost` argument
// sent by the browser, so a user could buy any cosmetic for 0 coins. Prices
// must live on the server. This script is the bridge — run it after editing
// src/lib/avatarCatalog.ts so the DB stays in sync with the UI.
//
//   node scripts/gen-avatar-catalog-sql.cjs
const fs = require("fs");
const path = require("path");

const root = path.resolve(__dirname, "..");
const source = path.join(root, "src", "lib", "avatarCatalog.ts");
const target = path.join(
  root,
  "supabase",
  "migrations",
  "20260921090200_avatar_catalog_server_prices.sql"
);

const src = fs.readFileSync(source, "utf8");
const lines = src.split(/\r?\n/);

const items = new Map(); // item_id -> { category, rarity, cost }
const skipped = [];

const field = (line, name) => {
  const m = line.match(new RegExp(name + ':\\s*"([^"]+)"'));
  return m ? m[1] : null;
};
const numField = (line, name) => {
  const m = line.match(new RegExp(name + ":\\s*(\\d+)"));
  return m ? Number(m[1]) : null;
};

for (const line of lines) {
  const trimmed = line.trim();

  // free("body_athletic", "Athletic", "body", ...) → cost 0, common
  const freeMatch = trimmed.match(/^free\(\s*"([^"]+)"\s*,\s*"[^"]*"\s*,\s*"([^"]+)"/);
  if (freeMatch) {
    items.set(freeMatch[1], { category: freeMatch[2], rarity: "common", cost: 0 });
    continue;
  }

  // { id: "x", name: "y", category: "c", rarity: "r", cost: N, ... }
  if (!trimmed.startsWith("{") || !/id:\s*"/.test(trimmed)) continue;
  const id = field(trimmed, "id");
  const category = field(trimmed, "category");
  const rarity = field(trimmed, "rarity");
  const cost = numField(trimmed, "cost");
  if (!id) continue;
  if (!category || !rarity || cost === null) {
    skipped.push({ id, reason: "missing category/rarity/cost (multi-line object?)" });
    continue;
  }
  items.set(id, { category, rarity, cost });
}

const rows = [...items.entries()].sort((a, b) => a[0].localeCompare(b[0]));
const esc = (s) => s.replace(/'/g, "''");

const sql = `-- GENERATED by scripts/gen-avatar-catalog-sql.cjs — do not hand-edit the rows.
-- Server-side source of truth for cosmetic prices, so purchase RPCs never trust
-- a price sent by the browser. Re-run the script after changing
-- src/lib/avatarCatalog.ts so the two stay in sync.

CREATE TABLE IF NOT EXISTS public.avatar_catalog (
  item_id   text PRIMARY KEY,
  category  text NOT NULL,
  rarity    text NOT NULL DEFAULT 'common',
  cost      integer NOT NULL DEFAULT 0 CHECK (cost >= 0),
  updated_at timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE public.avatar_catalog ENABLE ROW LEVEL SECURITY;

-- Catalog contents are public (the UI has to display prices).
DROP POLICY IF EXISTS "avatar_catalog_public_read" ON public.avatar_catalog;
CREATE POLICY "avatar_catalog_public_read" ON public.avatar_catalog
  FOR SELECT TO anon, authenticated USING (true);

GRANT SELECT ON public.avatar_catalog TO anon, authenticated;
GRANT ALL ON public.avatar_catalog TO service_role;

-- Only admins/backend may change prices.
DROP POLICY IF EXISTS "avatar_catalog_admin_write" ON public.avatar_catalog;
CREATE POLICY "avatar_catalog_admin_write" ON public.avatar_catalog
  FOR ALL TO authenticated
  USING (public.has_role(auth.uid(), 'admin'))
  WITH CHECK (public.has_role(auth.uid(), 'admin'));

INSERT INTO public.avatar_catalog (item_id, category, rarity, cost) VALUES
${rows.map(([id, v]) => `  ('${esc(id)}', '${esc(v.category)}', '${esc(v.rarity)}', ${v.cost})`).join(",\n")}
ON CONFLICT (item_id) DO UPDATE
  SET category = EXCLUDED.category,
      rarity   = EXCLUDED.rarity,
      cost     = EXCLUDED.cost,
      updated_at = now();

-- Keep every already-owned item valid: a cosmetic that predates this table
-- (or a retired id) is inserted at its last known price so nobody loses access.
INSERT INTO public.avatar_catalog (item_id, category, rarity, cost)
SELECT DISTINCT ai.item_id, ai.category, ai.rarity, 0
FROM public.avatar_items ai
ON CONFLICT (item_id) DO NOTHING;
`;

fs.writeFileSync(target, sql, "utf8");

console.log(`avatar catalog: ${rows.length} items → ${path.relative(root, target)}`);
console.log(`  free (cost 0): ${rows.filter(([, v]) => v.cost === 0).length}`);
console.log(`  by rarity: ${JSON.stringify(rows.reduce((acc, [, v]) => ({ ...acc, [v.rarity]: (acc[v.rarity] || 0) + 1 }), {}))}`);
if (skipped.length) {
  console.log(`  SKIPPED (${skipped.length}):`);
  for (const s of skipped) console.log(`    - ${s.id}: ${s.reason}`);
}
