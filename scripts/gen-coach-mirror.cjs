#!/usr/bin/env node
// ============================================================================
// gen-coach-mirror — copy the coach pricing config into the edge functions
// ----------------------------------------------------------------------------
// Supabase Edge Functions run on Deno and cannot import from `src/`. The money
// catalog solved this the same way (scripts/gen-money-mirror.cjs): one authored
// file, one generated mirror, and a test that fails when the mirror is stale.
//
// This generator is deliberately dumber than the money one. Instead of
// re-emitting selected constants and reimplementing a formula in the generator
// (which is a second place for the arithmetic to be wrong), it copies
// src/config/coachMarketplace.ts VERBATIM and puts a header on it. The body of
// the mirrored file is the authored file, byte for byte, so the price a coach
// sees and the price the server charges cannot disagree — there is only one
// implementation.
//
// That is only safe because the source file imports nothing, uses no Vite or
// Deno API, and is typed with plain TypeScript. Keep it that way: the moment it
// grows a dependency, this mirror stops being a copy and has to become a
// translation, and the "cannot drift" property is gone.
//
//   node scripts/gen-coach-mirror.cjs           write the mirror
//   node scripts/gen-coach-mirror.cjs --check   exit 1 if it is stale
// ============================================================================

const fs = require("node:fs");
const path = require("node:path");

const root = path.resolve(__dirname, "..");
const SOURCE = path.join(root, "src", "config", "coachMarketplace.ts");
const TARGET = path.join(root, "supabase", "functions", "_shared", "coachMarketplace.ts");

const HEADER = `// GENERATED by scripts/gen-coach-mirror.cjs from src/config/coachMarketplace.ts
// DO NOT EDIT THIS FILE. Edit the source and run \`npm run gen:coach\`.
//
// The body below is the authored file copied verbatim, so the commission the app
// displays and the commission the server charges are the same expression rather
// than two implementations that agree today. A test asserts this copy is current.

`;

/** Newlines are normalised to LF so a Windows checkout cannot produce a diff. */
const toLf = (text) => text.replace(/\r\n?/g, "\n");

function fail(message) {
  console.error(`gen-coach-mirror: ${message}`);
  process.exit(1);
}

function main() {
  const check = process.argv.includes("--check");

  if (!fs.existsSync(SOURCE)) {
    fail(`missing ${path.relative(root, SOURCE)} — the authored pricing config has gone`);
  }

  const expected = HEADER + toLf(fs.readFileSync(SOURCE, "utf8"));
  const current = fs.existsSync(TARGET) ? toLf(fs.readFileSync(TARGET, "utf8")) : null;

  if (current === expected) {
    console.log(`gen-coach-mirror: ${path.relative(root, TARGET)} is current`);
    return;
  }

  if (check) {
    fail(
      `${path.relative(root, TARGET)} is stale. Run \`npm run gen:coach\` and commit the result —\n` +
        "  the app and the edge functions would otherwise price a coach's plan differently.",
    );
  }

  fs.mkdirSync(path.dirname(TARGET), { recursive: true });
  fs.writeFileSync(TARGET, expected);
  console.log(`gen-coach-mirror: wrote ${path.relative(root, TARGET)} (${expected.length} bytes)`);
}

main();
