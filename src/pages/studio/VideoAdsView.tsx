// ============================================================================
// VideoAdsView — the real video-ad creation flow, wired to ads-video.
// ----------------------------------------------------------------------------
// One ask runs the whole pipeline: brief → REAL concept (script + storyboard
// via Gemini) → narration (ElevenLabs) → per-shot coverage (a screen recording
// from the asset library, or Veo shots whose quotes are paid because the
// athlete started the build) → render dispatch → live editor progress.
//
// Works with and without a screen recording:
//   • attach one at the brief and every storyboard shot is cut from it —
//     no Veo spend at all;
//   • leave it empty and each shot is generated by Veo, per-shot quoted
//     server-side and paid once, because the athlete asked for the build.
//
// Progress rules (every line on screen traces to a server response):
//   • the step log shows what the server actually said, plus elapsed seconds
//     where the provider offers no granular state — never a simulated percent;
//   • the render bar only appears once the editor has itself reported a
//     progress percent; before that the line says plainly that no progress
//     has been reported yet and shows how long it has been waiting;
//   • a Veo shot stays "generating" with its elapsed time until the server
//     moves it to ready or failed — never failed just because polling stopped;
//   • a failed step stops the pipeline and states exactly why; "Pick up where
//     it stopped" reuses everything that already succeeded instead of
//     rebuilding it.
// ============================================================================

import { useCallback, useEffect, useRef, useState } from "react";
import {
  Video as VideoIcon,
  Loader2,
  Sparkles,
  AlertCircle,
  CheckCircle2,
  XCircle,
  Mic,
  Download,
  RefreshCw,
  ClipboardList,
  FolderOpen,
  MonitorPlay,
  Play,
  ListTree,
  X,
} from "lucide-react";
import { Card, CardContent } from "@/components/ui/card";
import { Input } from "@/components/ui/input";
import { Badge } from "@/components/ui/badge";
import {
  generateVideoConcept,
  quoteShot,
  startShot,
  pollShot,
  validateVoiceover,
  generateVoiceover,
  uploadNarration,
  renderVideo,
  jobStatus,
  type VideoConceptResult,
  type VideoStoryboardScene,
} from "./videoAdsApi";
import { listLibrary, type LibraryItem } from "./api";
import { Dialog, DialogContent, DialogHeader, DialogTitle } from "@/components/ui/dialog";

const CARD = "bg-white/5 border border-white/10";
const ACCENT = "bg-[#8505D5] text-white";

interface ShotRow {
  scene: VideoStoryboardScene;
  videoUri: string | null;
  state: "pending" | "generating" | "ready" | "failed";
  error?: string | null;
  shotId?: string;
  operationId?: string;
}

/** One line in the step log. `detail` is a server response, a refusal reason,
 *  or an elapsed-seconds counter — it is never invented to look busy. */
interface StepEntry {
  id: string;
  label: string;
  state: "done" | "running" | "failed";
  detail: string | null;
  startedAt: number;
}

/** How long the client keeps asking for one Veo shot before it hands control
 *  back honestly (the provider can still finish it later; the row stays
 *  "generating" — truth, not failure). */
const SHOT_POLL_MAX_MS = 6 * 60 * 1000;
const SHOT_POLL_INTERVAL_MS = 4000;
/** How long the client keeps asking the editor for a render update before the
 *  UI stops and says the editor has not reported back — the status on the card
 *  stays whatever the server last said. */
const RENDER_POLL_MAX_MS = 15 * 60 * 1000;
const RENDER_POLL_INTERVAL_MS = 2500;

const secs = (ms: number) => `${Math.max(1, Math.round(ms / 1000))}s`;

export default function VideoAdsView({
  onOpenChat,
  /** A brief written in the Creative Assistant, dropped here when the chat's
   *  video plan continues into this workspace. Consumed once, then cleared. */
  chatBrief,
  onConsumeChatBrief,
}: {
  onOpenChat: () => void;
  chatBrief?: string | null;
  onConsumeChatBrief?: () => void;
}) {
  // ------------------------------------------------------------------ brief
  const [request, setRequest] = useState("");

  // Accept a brief handed over from the Creative Assistant: prefill the brief
  // field (never auto-start anything — generation stays behind the quote and
  // its explicit start) and clear the handover.
  useEffect(() => {
    if (typeof chatBrief === "string" && chatBrief.trim()) {
      setRequest((current) => (current.trim() ? current : chatBrief.trim()));
      onConsumeChatBrief?.();
    }
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [chatBrief]);
  const [durationSeconds, setDurationSeconds] = useState("15");
  const [callToAction, setCallToAction] = useState("Join the waitlist");
  const [concept, setConcept] = useState<VideoConceptResult | null>(null);
  const [shots, setShots] = useState<ShotRow[]>([]);
  const [narrationPath, setNarrationPath] = useState<string | null>(null);
  const [voiceCharacters, setVoiceCharacters] = useState<number | null>(null);
  const [renderJob, setRenderJob] = useState<{
    jobId: string;
    state: string;
    progress: number;
    stage: string | null;
    error: string | null;
    publicUrl: string | null;
    startedAt: number;
  } | null>(null);
  const [error, setError] = useState<string | null>(null);
  const [steps, setSteps] = useState<StepEntry[]>([]);
  const [pipelineRunning, setPipelineRunning] = useState(false);
  const pipelineRunRef = useRef(0);
  // A 1-second clock so every "elapsed" label ticks live instead of only
  // updating when a server response happens to re-render the view.
  const [now, setNow] = useState(() => Date.now());
  // The screen recording chosen at brief time: when set, every storyboard shot
  // is cut from it and the pipeline spends nothing on Veo.
  const [briefRecording, setBriefRecording] = useState<LibraryItem | null>(null);
  // Library assets (screen recordings / clips): attachable to a single shot in
  // place of a Veo generation — that shot then needs no provider spend at all.
  const [libPicker, setLibPicker] = useState<number | null>(null);
  const [libItems, setLibItems] = useState<LibraryItem[] | null>(null);
  const [libError, setLibError] = useState<string | null>(null);
  const [briefPickerOpen, setBriefPickerOpen] = useState(false);
  const pollTimersRef = useRef<ReturnType<typeof setTimeout>[]>([]);

  useEffect(() => () => {
    pipelineRunRef.current += 1; // invalidate any in-flight pipeline loops
    pollTimersRef.current.forEach(clearTimeout);
  }, []);

  // The live clock runs while anything is building, so the step log and the
  // shot rows show genuinely moving elapsed time.
  useEffect(() => {
    if (!pipelineRunning) return;
    setNow(Date.now());
    const t = setInterval(() => setNow(Date.now()), 1000);
    return () => clearInterval(t);
  }, [pipelineRunning]);

  const duration = Number(durationSeconds);
  const durInvalid = !duration || duration < 6 || duration > 60;
  const canStart = request.trim().length >= 4 && !durInvalid && !pipelineRunning;

  // ------------------------------------------------------------ step log
  const beginStep = (id: string, label: string) =>
    setSteps((rows) => [
      ...rows.filter((r) => r.id !== id),
      { id, label, state: "running" as const, detail: null, startedAt: Date.now() },
    ]);
  const finishStep = (id: string, detail: string) =>
    setSteps((rows) => rows.map((r) => (r.id === id ? { ...r, state: "done", detail } : r)));
  const failStep = (id: string, detail: string) =>
    setSteps((rows) => rows.map((r) => (r.id === id ? { ...r, state: "failed", detail } : r)));
  const noteStep = (id: string, detail: string) =>
    setSteps((rows) =>
      rows.map((r) => (r.id === id && r.state === "running" ? { ...r, detail } : r)),
    );

  // ------------------------------------------------------------ library assets
  const loadLibrary = useCallback(async (): Promise<LibraryItem[]> => {
    if (libItems !== null) return libItems;
    try {
      const items = await listLibrary({ kind: "video" });
      setLibItems(items);
      return items;
    } catch (e) {
      const msg = e instanceof Error ? e.message : "Could not load the asset library.";
      setLibError(msg);
      return [];
    }
  }, [libItems]);

  // An owner-storage path: the picker hands over the PRIVATE ads-bucket path
  // and the render step signs it server-side for the owner only; nothing goes
  // public. Both the working list and the UI state are kept in step.
  const applyClip = (work: ShotRow[], index: number, item: LibraryItem) => {
    const source = `ads/${item.storage_path}`;
    work[index] = {
      ...work[index],
      scene: { ...work[index].scene, source, sourceType: "user_upload" },
      videoUri: source,
      state: "ready",
      error: null,
    };
    setShots([...work]);
    setLibPicker(null);
  };

  // ------------------------------------------------------------ library pickers
  const openLibraryPicker = async (index: number) => {
    if (pipelineRunning) return;
    setError(null);
    setLibPicker(index);
    await loadLibrary();
  };

  const pickBriefRecording = async (item: LibraryItem) => {
    setBriefRecording(item);
    setBriefPickerOpen(false);
    setError(null);
    await loadLibrary();
  };

  // ------------------------------------------------------------ concept
  const createConcept = async (): Promise<VideoConceptResult | null> => {
    setConcept(null);
    setShots([]);
    setNarrationPath(null);
    setVoiceCharacters(null);
    setRenderJob(null);
    setError(null);
    beginStep("concept", "Write the concept — step 1, free (no provider spend)");
    try {
      const c = await generateVideoConcept({
        prompt: request.trim(),
        durationSeconds: duration,
        callToAction: callToAction.trim() || "Join the waitlist",
      });
      setConcept(c);
      setShots(c.storyboard.map((scene) => ({ scene, videoUri: scene.source || null, state: "pending" })));
      const fallback = c.storyboardSource !== "model";
      finishStep(
        "concept",
        `Done — script written and ${c.storyboard.length} shot plan${c.storyboard.length === 1 ? "" : "s"} set (${fallback ? "deterministic fallback planner" : "model-written storyboard"})`,
      );
      if (fallback) {
        setError("The model could not write a storyboard, so the server's deterministic fallback planner produced the shot plan. It is usable; a second run may give better visuals.");
      }
      return c;
    } catch (e) {
      const msg = e instanceof Error ? e.message : "Concept generation failed.";
      failStep("concept", `${msg} Nothing was spent.`);
      setError(msg);
      return null;
    }
  };

  // ------------------------------------------------------------ voiceover
  const makeVoiceover = async (c: VideoConceptResult): Promise<string | null> => {
    beginStep("voice", "Write the narration — step 2, billed per character");
    try {
      const quote = await validateVoiceover(c.concept.script);
      if (!quote.valid) {
        const msg = "The server refused the script for the voiceover brand checks — nothing was billed. Revise the brief and start again.";
        failStep("voice", msg);
        setError(msg);
        return null;
      }
      noteStep("voice", `The server validated the script at ${quote.characters} billed characters — generating the audio now`);
      const audio = await generateVoiceover({ text: c.concept.script });
      const path = await uploadNarration(audio.audio, audio.mimeType);
      setNarrationPath(path);
      setVoiceCharacters(audio.characters);
      finishStep("voice", `Done — ${audio.characters} characters billed${audio.cached ? " (served from the provider's cache)" : ""} | stored at ${path}`);
      return path;
    } catch (e) {
      const msg = e instanceof Error ? e.message : "Narration generation failed.";
      failStep("voice", msg);
      setError(msg);
      return null;
    }
  };

  // ------------------------------------------------------------ shots
  /** Waits for one in-flight Veo shot, keeping the step log honest: "still
   *  generating · 34s elapsed" comes from the server's own poll response; the
   *  server turning the shot over to failed is the only thing that marks it
   *  failed here. Returns whether the shot ended up ready. */
  const refreshOne = (runId: number, work: ShotRow[], index: number, shotId: string, operationId: string): Promise<boolean> =>
    new Promise((resolve) => {
      const started = Date.now();
      const stepId = `shot-${index}`;
      const tick = async () => {
        if (pipelineRunRef.current !== runId) { resolve(false); return; }
        try {
          const p = await pollShot(shotId, operationId);
          if (pipelineRunRef.current !== runId) { resolve(false); return; }
          if (p.done) {
            if (p.state === "failed") {
              const msg = p.error ?? "The server reported this shot as failed";
              work[index] = { ...work[index], state: "failed", error: msg };
              setShots([...work]);
              failStep(stepId, `${msg} Nothing further was spent on this shot.`);
              resolve(false);
            } else {
              work[index] = { ...work[index], state: "ready", videoUri: p.videoUri ?? work[index].videoUri, error: null };
              setShots([...work]);
              finishStep(stepId, "Done — the Veo clip is stored and attached");
              resolve(true);
            }
            return;
          }
          work[index] = { ...work[index], state: "generating", error: null };
          setShots([...work]);
          noteStep(stepId, `Veo is still generating this shot — ${secs(Date.now() - started)} elapsed (status straight from the server's poll)`);
        } catch (e) {
          const msg = e instanceof Error ? e.message : "The status check failed";
          work[index] = { ...work[index], state: "failed", error: msg };
          setShots([...work]);
          failStep(stepId, msg);
          resolve(false);
          return;
        }
        if (Date.now() - started >= SHOT_POLL_MAX_MS) {
          // Still genuinely running, but beyond the client's watch window. The
          // row stays "generating" (the server's truth) and the pipeline stops
          // with an honest note — a retry re-checks without paying again.
          failStep(
            stepId,
            `The server still reports this shot generating after ${secs(SHOT_POLL_MAX_MS)} of checking — it may still finish on its own. “Pick up where it stopped” re-checks it without paying for it again.`,
          );
          resolve(false);
          return;
        }
        pollTimersRef.current.push(setTimeout(tick, SHOT_POLL_INTERVAL_MS));
      };
      void tick();
    });

  /** Quotes one shot server-side, pays it (the athlete asked for the build —
   *  that is stated in the log), and waits for Veo to finish it. */
  const generateShot = async (runId: number, work: ShotRow[], index: number): Promise<boolean> => {
    const row = work[index];
    const stepId = `shot-${index}`;
    beginStep(stepId, `Generate shot ${row.scene.shot} with Veo — ${row.scene.durationSeconds}s`);
    try {
      const q = await quoteShot({ conceptId: concept?.conceptId ?? "", shot: row.scene.shot, placement: "reels" });
      if (pipelineRunRef.current !== runId) return false;
      noteStep(stepId, `The server quoted this shot at ~$${(q.estimatedCostUsd ?? 0).toFixed(2)} — paying it and generating straight away, no approval pause`);
      const s = await startShot(q);
      if (pipelineRunRef.current !== runId) return false;
      work[index] = { ...work[index], state: "generating", shotId: s.shotId, operationId: s.operationId, error: null };
      setShots([...work]);
      return await refreshOne(runId, work, index, s.shotId, s.operationId);
    } catch (e) {
      const msg = e instanceof Error ? e.message : "The shot could not be generated.";
      failStep(stepId, msg);
      work[index] = { ...work[index], state: "failed", error: msg };
      setShots([...work]);
      return false;
    }
  };

  // ------------------------------------------------------------ render
  const doRender = async (runId: number, work: ShotRow[], narration: string | null, c: VideoConceptResult): Promise<boolean> => {
    beginStep("render", "Render the finished ad — 1 credit to dispatch");
    try {
      const assetPaths: Record<string, string> = {};
      for (const s of work) if (s.videoUri) assetPaths[String(s.scene.shot)] = s.videoUri;
      const notReady = work.filter((s) => !s.videoUri).length;
      if (notReady > 0) {
        const msg = `${notReady} shot${notReady === 1 ? "" : "s"} still has no clip — the server refuses a render without them; nothing was charged for that refusal.`;
        failStep("render", msg);
        setError(msg);
        return false;
      }
      const j = await renderVideo({
        conceptId: c.conceptId,
        voiceover: c.concept.script,
        captions: c.captions,
        narrationPath: narration,
        assetPaths,
      });
      if (pipelineRunRef.current !== runId) return false;
      setRenderJob({
        jobId: j.jobId,
        state: j.state,
        progress: typeof j.progress === "number" ? j.progress : 0,
        stage: null,
        error: null,
        publicUrl: null,
        startedAt: Date.now(),
      });

      const waitingStarted = Date.now();
      for (;;) {
        if (pipelineRunRef.current !== runId) return false;
        if (Date.now() - waitingStarted >= RENDER_POLL_MAX_MS) {
          const msg = "The editor has not reported anything back after 15 minutes of checking. The job stays queued server-side; “Pick up where it stopped” re-checks it.";
          failStep("render", msg);
          setError(msg);
          return false;
        }
        await new Promise((r) => setTimeout(r, RENDER_POLL_INTERVAL_MS));
        if (pipelineRunRef.current !== runId) return false;
        const st = await jobStatus(j.jobId);
        if (pipelineRunRef.current !== runId) return false;
        setRenderJob((prev) =>
          prev
            ? {
                ...prev,
                state: st.status,
                progress: typeof st.progress === "number" ? st.progress : prev.progress,
                stage: st.stage ?? prev.stage,
                error: st.error ?? null,
                publicUrl: st.publicUrl ?? prev.publicUrl,
              }
            : prev,
        );
        if (st.status === "failed") {
          const msg = st.error ?? "The server reported the render as failed";
          failStep("render", msg);
          setError(msg);
          return false;
        }
        if (st.status === "done") {
          finishStep(
            "render",
            st.publicUrl
              ? "Done — the finished ad is ready to watch (link below)"
              : "The server marked the edit done but attached no watchable file — the link below explains what is missing.",
          );
          return true;
        }
        // Live detail from the editor only; before it reports anything the line
        // says exactly that instead of showing motion it did not send.
        noteStep(
          "render",
          st.stage
            ? `${st.stage}${typeof st.progress === "number" && st.progress > 0 ? ` · editor-reported ${st.progress}%` : ""} · ${secs(Date.now() - waitingStarted)} since dispatch`
            : `${st.status === "editing" ? "the editor picked the job up" : "queued at the editor"} — no progress reported yet · ${secs(Date.now() - waitingStarted)} since dispatch`,
        );
      }
    } catch (e) {
      const msg = e instanceof Error ? e.message : "Render could not start.";
      failStep("render", msg);
      setError(msg);
      return false;
    }
  };

  // ------------------------------------------------------------ pipeline
  const runPipeline = async () => {
    if (pipelineRunning || !canStart) return;
    const runId = pipelineRunRef.current;
    setPipelineRunning(true);
    setError(null);
    try {
      // Concept — reuse the one that already succeeded on a resumed run.
      let c = concept;
      let work = shots;
      if (!c) {
        c = await createConcept();
        if (!c) return;
        work = c.storyboard.map((scene) => ({ scene, videoUri: scene.source || null, state: "pending" }));
        setShots(work);
      }

      // Narration — only if the resumed run does not already have it.
      let narration = narrationPath;
      if (!narration) {
        narration = await makeVoiceover(c);
        if (!narration) return;
      }

      // Shot coverage: with a recording attached every storyboard shot is cut
      // from it (no provider spend); without one, Veo generates (and is paid
      // for) each shot, per-shot quoted server-side.
      if (briefRecording) {
        const stepId = "recordings";
        if (!stepForDone(stepId)) beginStep(stepId, "Cover the shots from your screen recording");
        for (let i = 0; i < work.length; i++) applyClip(work, i, briefRecording);
        finishStep(stepId, `Every shot is cut from your recording “${briefRecording.name}” — no provider spend for the ${work.length} shot${work.length === 1 ? "" : "s"}. The recording stays private to your account.`);
      } else {
        for (let i = 0; i < work.length; i++) {
          if (work[i].state === "ready") {
            if (!stepForDone(`shot-${i}`)) {
              finishStep(`shot-${i}`, work[i].videoUri?.startsWith("ads/") ? "Ready — covered by a library clip (no provider spend)" : "Ready — the Veo clip is attached");
            }
            continue;
          }
          if (!(await generateShot(runId, work, i))) return;
        }
      }

      if (!(await doRender(runId, work, narration, c))) return;
    } finally {
      setPipelineRunning(false);
    }
  };

  const stepForDone = (id: string) => steps.find((s) => s.id === id && s.state === "done");

  // Manual single-shot controls: a click runs the shot through quote → pay →
  // generate in one go — the quote is shown in the log, never turned into a
  // wait. They never run while the pipeline is already going.
  const generateOneShot = async (index: number) => {
    if (!concept || pipelineRunning) return;
    await generateShot(pipelineRunRef.current, shots, index);
  };

  const retryShot = async (index: number) => {
    if (pipelineRunning) return;
    setShots((rows) => rows.map((r, i) => (i === index ? { ...r, state: "pending", error: null } : r)));
    void generateOneShot(index);
  };

  const readyShots = shots.filter((s) => s.state === "ready").length;
  const failedShots = shots.filter((s) => s.state === "failed").length;
  const currentRunningStep = steps.find((s) => s.state === "running");
  const finishedSteps = steps.filter((s) => s.state === "done" || s.state === "failed").length;

  // ------------------------------------------------------------------ view
  return (
    <div className="mx-auto max-w-3xl space-y-4">
      {/* -------- brief -------- */}
      <Card className={CARD}>
        <CardContent className="space-y-4 p-6">
          <div className="flex items-center gap-2">
            <VideoIcon className="h-5 w-5" />
            <h2 className="font-medium">New video ad — real pipeline</h2>
          </div>
          <div>
            <label className="mb-1 block text-xs text-white/60">What should the ad show?</label>
            <textarea
              className="min-h-[70px] w-full rounded-lg bg-black/40 px-3 py-2 text-sm"
              value={request}
              onChange={(e) => setRequest(e.target.value)}
              placeholder="Athlete premium spot: blue-hour track session, measured and confident."
            />
          </div>
          <div className="grid grid-cols-1 gap-3 sm:grid-cols-2">
            <div>
              <label className="mb-1 block text-xs text-white/60">Duration (6–60 s)</label>
              <Input className="bg-black/40" type="number" min={6} max={60} value={durationSeconds} onChange={(e) => setDurationSeconds(e.target.value)} />
            </div>
            <div>
              <label className="mb-1 block text-xs text-white/60">Call to action</label>
              <Input className="bg-black/40" value={callToAction} onChange={(e) => setCallToAction(e.target.value)} />
            </div>
          </div>

          {/* Screen recording: the with-and-without switch */}
          <div className="rounded-lg bg-black/20 p-3">
            <p className="mb-1 text-sm font-medium">Screen recording (optional)</p>
            <p className="mb-2 text-xs text-white/50">
              {briefRecording
                ? "Every storyboard shot will be cut from this recording — nothing is spent on Veo. Clear it to generate the shots with Veo instead."
                : "Attach one and the ad is cut from your recording — no Veo spend. Leave it empty and each shot is generated by Veo (per-shot provider spend). Recordings are made in the Asset Library."}
            </p>
            {briefRecording ? (
              <div className="flex items-center gap-2">
                <MonitorPlay className="h-4 w-4 shrink-0 text-[#d9b3ff]" />
                <span className="min-w-0 truncate text-sm">{briefRecording.name}</span>
                <button onClick={() => setBriefPickerOpen(true)} className="rounded bg-white/10 px-2.5 py-1 text-xs text-white/80 hover:bg-white/20">Change</button>
                <button onClick={() => setBriefRecording(null)} className="flex items-center gap-1 rounded bg-white/10 px-2.5 py-1 text-xs text-white/70 hover:bg-white/20">
                  <X className="h-3 w-3" /> Clear
                </button>
              </div>
            ) : (
              <button onClick={() => setBriefPickerOpen(true)} className="rounded bg-white/10 px-3 py-1.5 text-xs text-white/80 hover:bg-white/20">
                <FolderOpen className="mr-1 inline h-3.5 w-3.5" /> Choose a screen recording from the asset library
              </button>
            )}
          </div>

          <p className="text-[10px] text-white/40">
            One click runs the whole build with no approval pauses: concept (free) → narration (billed per character) → shots (each quoted and paid immediately) → render (dispatch, then the ads editor reports progress live). Every line below tells you what the server actually said.
          </p>
          <div className="flex items-center gap-3">
            <button
              onClick={() => void runPipeline()}
              disabled={!canStart}
              className={`rounded-lg px-4 py-2 text-sm ${ACCENT} disabled:opacity-40`}
            >
              {pipelineRunning ? <Loader2 className="mr-1.5 inline h-4 w-4 animate-spin" /> : <Play className="mr-1.5 inline h-4 w-4" />} {pipelineRunning ? "Building…" : "Build the ad"}
            </button>
            {steps.length > 0 && !pipelineRunning && steps.some((s) => s.state === "failed") && (
              <button
                onClick={() => void runPipeline()}
                className="rounded-lg border border-[#8505D5]/50 bg-[#8505D5]/10 px-4 py-2 text-sm text-[#d9b3ff] hover:bg-[#8505D5]/20"
              >
                <RefreshCw className="mr-1.5 inline h-3.5 w-3.5" /> Pick up where it stopped
              </button>
            )}
          </div>
          {pipelineRunning && currentRunningStep && (
            <div className="flex items-center gap-2 rounded-lg border border-amber-300/20 bg-amber-300/5 px-3 py-2 text-sm text-amber-200/90">
              <Loader2 className="h-4 w-4 shrink-0 animate-spin" />
              <span className="min-w-0 flex-1">Now working on: {currentRunningStep.label}</span>
              <span className="shrink-0 tabular-nums text-xs text-amber-200/60">{secs(now - currentRunningStep.startedAt)}</span>
            </div>
          )}
          {durInvalid && <p className="text-xs text-red-400">Duration must be between 6 and 60 seconds.</p>}
        </CardContent>
      </Card>

      {error && (
        <Card className="border border-red-500/30">
          <CardContent className="flex items-start gap-2 p-3 text-sm text-red-300">
            <AlertCircle className="mt-0.5 h-4 w-4 shrink-0" />
            <span className="min-w-0">{error}</span>
            <button className="ml-auto shrink-0 underline" onClick={() => setError(null)}>dismiss</button>
          </CardContent>
        </Card>
      )}

      {/* -------- honest step log -------- */}
      {steps.length > 0 && (
        <Card className={CARD}>
          <CardContent className="space-y-2 p-4 text-sm">
            <div className="flex items-center gap-2">
              <h3 className="flex items-center gap-2 font-medium"><ListTree className="h-4 w-4" /> What is happening</h3>
              <span className="ml-auto text-[10px] tabular-nums text-white/40">{finishedSteps}/{steps.length} steps settled</span>
            </div>
            <div className="h-1.5 w-full overflow-hidden rounded bg-black/40">
              <div className="h-full rounded bg-[#8505D5] transition-all duration-500" style={{ width: `${Math.round((finishedSteps / Math.max(1, steps.length)) * 100)}%` }} />
            </div>
            <ol className="space-y-2">
              {steps.map((s) => (
                <li key={s.id} className="rounded-lg bg-black/20 p-2.5">
                  <div className="flex items-center gap-2 text-xs">
                    {s.state === "running" && <Loader2 className="h-3.5 w-3.5 shrink-0 animate-spin text-amber-300" />}
                    {s.state === "done" && <CheckCircle2 className="h-3.5 w-3.5 shrink-0 text-emerald-400" />}
                    {s.state === "failed" && <XCircle className="h-3.5 w-3.5 shrink-0 text-red-400" />}
                    <span className="min-w-0 flex-1">{s.label}</span>
                    <span className="shrink-0 text-[10px] tabular-nums text-white/40">
                      {s.state === "running" ? `${secs(now - s.startedAt)} elapsed` : s.state}
                    </span>
                  </div>
                  {s.detail && (
                    <p className={`mt-1 pl-5 text-[11px] ${s.state === "running" ? "text-amber-200/70" : s.state === "failed" ? "text-red-300/80" : "text-white/60"}`}>
                      {s.detail}
                    </p>
                  )}
                </li>
              ))}
            </ol>
          </CardContent>
        </Card>
      )}

      {/* -------- concept -------- */}
      {concept && (
        <Card className={CARD}>
          <CardContent className="space-y-2 p-4 text-sm">
            <div className="flex flex-wrap items-center gap-2">
              <Sparkles className="h-4 w-4" />
              <span className="font-medium">Concept</span>
              <Badge variant="outline" className="border-white/20 text-white/70">
                storyboard: {concept.storyboardSource === "model" ? "model" : "deterministic fallback"}
              </Badge>
              <Badge variant="outline" className="border-white/10 text-[10px] text-white/50">
                id {concept.conceptId.slice(0, 8)}…
              </Badge>
            </div>
            <p><span className="text-white/60">Hook:</span> {concept.concept.hook}</p>
            <p><span className="text-white/60">Core message:</span> {concept.concept.message}</p>
            <p className="whitespace-pre-wrap rounded-lg bg-black/30 p-2 text-xs text-white/80">{concept.concept.script}</p>
            <div className="flex flex-wrap gap-1">
              {concept.captions.map((cpt, i) => (
                <Badge key={i} variant="outline" className="border-white/10 text-[10px] text-white/60">
                  {cpt.startSeconds}s–{cpt.endSeconds}s · {cpt.text}
                </Badge>
              ))}
            </div>
          </CardContent>
        </Card>
      )}

      {/* -------- shots -------- */}
      {concept && (
        <Card className={CARD}>
          <CardContent className="space-y-3 p-4 text-sm">
            <div className="flex flex-wrap items-center justify-between gap-2">
              <h3 className="flex items-center gap-2 font-medium">
                <ClipboardList className="h-4 w-4" /> Shots ({readyShots}/{shots.length} ready{failedShots ? `, ${failedShots} failed` : ""})
              </h3>
              <span className="text-[10px] text-white/40">Each shot is one Veo generation or one library clip.</span>
            </div>
            {shots.map((row, i) => (
              <div key={row.scene.shot} className="rounded-lg bg-black/20 p-3">
                <div className="flex flex-wrap items-center gap-2 text-xs">
                  <span className="rounded bg-white/10 px-1.5 py-0.5">shot {row.scene.shot} · {row.scene.durationSeconds}s</span>
                  <span className="text-white/70">{row.scene.visualDescription || "(no visual description — this shot cannot be generated yet)"}</span>
                  <span className={`ml-auto ${row.state === "failed" ? "text-red-400" : row.state === "ready" ? "text-emerald-400" : row.state === "generating" ? "text-amber-300" : "text-white/50"}`}>
                    {row.state}
                  </span>
                </div>
                {row.error && <p className="mt-1 text-xs text-red-400">{row.error}</p>}
                <div className="mt-2 flex flex-wrap gap-1.5">
                  {row.state === "pending" && !pipelineRunning && (
                    <button onClick={() => void generateOneShot(i)} className={`rounded px-2.5 py-1 text-xs ${ACCENT}`}>
                      Generate this shot
                    </button>
                  )}
                  {(row.state === "pending" || row.state === "failed") && !pipelineRunning && (
                    <button onClick={() => void openLibraryPicker(i)} className="rounded bg-white/10 px-2.5 py-1 text-xs text-white/80 hover:bg-white/20">
                      <FolderOpen className="mr-1 inline h-3 w-3" /> Use a library clip
                    </button>
                  )}
                  {row.state === "generating" && (
                    <span className="flex items-center gap-1 text-xs text-amber-300"><Loader2 className="h-3 w-3 animate-spin" /> the server says this shot is still generating…</span>
                  )}
                  {row.state === "ready" && (
                    <span className="flex items-center gap-1 text-xs text-emerald-400">
                      <CheckCircle2 className="h-3 w-3" /> {row.videoUri?.startsWith("ads/") ? "library clip attached" : "clip ready"}
                    </span>
                  )}
                  {row.state === "failed" && !pipelineRunning && (
                    <button onClick={() => void retryShot(i)} className="rounded bg-white/10 px-2.5 py-1 text-xs text-white/80">
                      <RefreshCw className="mr-1 inline h-3 w-3" /> Retry this shot
                    </button>
                  )}
                </div>
              </div>
            ))}
          </CardContent>
        </Card>
      )}

      {/* -------- narration -------- */}
      {concept && (
        <Card className={CARD}>
          <CardContent className="space-y-2 p-4 text-sm">
            <h3 className="flex items-center gap-2 font-medium"><Mic className="h-4 w-4" /> Narration (ElevenLabs)</h3>
            {narrationPath ? (
              <p className="flex items-center gap-2 text-xs text-emerald-400">
                <CheckCircle2 className="h-3.5 w-3.5" /> Narration stored ({voiceCharacters ?? "?"} billed characters) → <code className="text-[10px]">{narrationPath}</code>
              </p>
            ) : (
              <p className="text-[11px] text-white/50">
                {pipelineRunning
                  ? "Building the narration now — the step log shows exactly what the server reported."
                  : "The build runs this automatically when you click “Build the ad” — the server bills per character and reports the count."}
              </p>
            )}
          </CardContent>
        </Card>
      )}

      {/* -------- render -------- */}
      {concept && (
        <Card className={CARD}>
          <CardContent className="space-y-2 p-4 text-sm">
            <h3 className="flex items-center gap-2 font-medium"><Download className="h-4 w-4" /> Render</h3>
            {!renderJob ? (
              <p className="text-[11px] text-white/50">The build dispatches the render automatically once every shot has a clip. The editor then reports its own progress live in the step log.</p>
            ) : (
              <div className="space-y-2 text-xs">
                <div className="flex flex-wrap items-center gap-2">
                  {renderJob.state === "failed" ? <XCircle className="h-3.5 w-3.5 text-red-400" /> : renderJob.state === "done" ? <CheckCircle2 className="h-3.5 w-3.5 text-emerald-400" /> : <Loader2 className="h-3.5 w-3.5 animate-spin text-amber-300" />}
                  <span>
                    render job {renderJob.jobId.slice(0, 8)}… —{" "}
                    {renderJob.state === "queued" ? "queued for the editor"
                      : renderJob.state === "handed_to_manus" ? "waiting for the ads editor to pick it up"
                      : renderJob.state === "editing" ? "the editor is working on your ad"
                      : renderJob.state === "done" ? "finished — your ad is ready to watch"
                      : renderJob.state === "failed" ? "failed"
                      : renderJob.state}
                  </span>
                  {renderJob.state !== "done" && renderJob.state !== "failed" && (
                    <span className="ml-auto tabular-nums text-white/50">{secs(now - renderJob.startedAt)} since dispatch</span>
                  )}
                </div>
                {/* A bar only from the editor's own number: before it reports a
                    percent the honest answer is "no progress reported yet". */}
                {renderJob.state !== "done" && renderJob.state !== "failed" && renderJob.progress > 0 && (
                  <div className="h-2 w-full overflow-hidden rounded bg-black/40">
                    <div className="h-full rounded bg-[#8505D5] transition-all duration-500" style={{ width: `${Math.min(99, renderJob.progress)}%` }} />
                  </div>
                )}
                {renderJob.state === "editing" && renderJob.stage && (
                  <p className="text-[10px] text-amber-200/80">↳ {renderJob.stage}</p>
                )}
                {renderJob.state !== "done" && renderJob.state !== "failed" && !renderJob.stage && renderJob.progress === 0 && (
                  <p className="text-[10px] text-white/40">The editor has not reported a progress percent yet — the step log shows elapsed time since dispatch instead of a made-up number.</p>
                )}
                {renderJob.state === "failed" && renderJob.error && (
                  <p className="rounded bg-black/30 px-2 py-1.5 text-red-300">{renderJob.error}</p>
                )}
                {renderJob.state === "failed" && (
                  <p className="text-[10px] text-white/40">Nothing was lost: the concept, clips and narration are all still saved — “Pick up where it stopped” queues the render again.</p>
                )}
                {renderJob.state === "done" && (
                  renderJob.publicUrl ? (
                    <a href={renderJob.publicUrl} target="_blank" rel="noreferrer" className="inline-flex items-center gap-1.5 rounded bg-emerald-600/20 px-3 py-1.5 text-xs font-medium text-emerald-200 underline decoration-emerald-500/50 hover:bg-emerald-600/30">
                      <MonitorPlay className="h-3.5 w-3.5" /> Watch the finished ad
                    </a>
                  ) : (
                    <p className="text-[10px] text-amber-300/80">The editor reported the edit finished, but attached no watchable file — use “Pick up where it stopped” to re-check.</p>
                  )
                )}
              </div>
            )}
          </CardContent>
        </Card>
      )}

      {/* -------- library clip pickers -------- */}
      <Dialog open={libPicker !== null} onOpenChange={(open) => !open && setLibPicker(null)}>
        <DialogContent className="w-[min(94vw,560px)] border-white/15 bg-[#0d1017] text-white">
          <DialogHeader>
            <DialogTitle>Choose a clip from your asset library</DialogTitle>
          </DialogHeader>
          {libItems === null ? (
            <div className="flex items-center gap-2 text-xs text-white/60">
              <Loader2 className="h-3.5 w-3.5 animate-spin" /> {libError ?? "Loading the library…"}
            </div>
          ) : libItems.length === 0 ? (
            <p className="text-sm text-white/60">No video assets in your library yet. Upload a screen recording in the Asset Library and it will appear here.</p>
          ) : (
            <div className="max-h-[50vh] space-y-1.5 overflow-y-auto">
              {libItems.map((item) => (
                <button key={item.id} onClick={() => libPicker !== null && applyClip(shots, libPicker, item)} className="flex w-full items-center gap-2 rounded-lg bg-white/5 px-3 py-2 text-left text-sm hover:bg-white/10">
                  <MonitorPlay className="h-4 w-4 shrink-0 text-[#d9b3ff]" />
                  <span className="min-w-0 flex-1 truncate">{item.name}</span>
                  {(item.metadata as Record<string, unknown> | undefined)?.screenRecording === true && (
                    <span className="shrink-0 rounded border border-[#8505D5]/40 bg-[#8505D5]/10 px-1.5 py-0.5 text-[10px] text-[#d9b3ff]">screen recording</span>
                  )}
                  <span className="shrink-0 text-[10px] text-white/40">{item.status}</span>
                </button>
              ))}
            </div>
          )}
          <p className="text-[10px] text-white/40">Library clips cover a shot directly — no Veo spend is made for it, and the clip stays private to your account.</p>
        </DialogContent>
      </Dialog>

      <Dialog open={briefPickerOpen} onOpenChange={setBriefPickerOpen}>
        <DialogContent className="w-[min(94vw,560px)] border-white/15 bg-[#0d1017] text-white">
          <DialogHeader>
            <DialogTitle>Attach a screen recording for the whole ad</DialogTitle>
          </DialogHeader>
          {libItems === null ? (
            <div className="flex items-center gap-2 text-xs text-white/60">
              <Loader2 className="h-3.5 w-3.5 animate-spin" /> {libError ?? "Loading the library…"}
            </div>
          ) : libItems.length === 0 ? (
            <p className="text-sm text-white/60">No video assets in your library yet. Upload a screen recording in the Asset Library and it will appear here; without one the shots are generated by Veo.</p>
          ) : (
            <div className="max-h-[50vh] space-y-1.5 overflow-y-auto">
              {libItems.map((item) => (
                <button key={item.id} onClick={() => void pickBriefRecording(item)} className="flex w-full items-center gap-2 rounded-lg bg-white/5 px-3 py-2 text-left text-sm hover:bg-white/10">
                  <MonitorPlay className="h-4 w-4 shrink-0 text-[#d9b3ff]" />
                  <span className="min-w-0 flex-1 truncate">{item.name}</span>
                  {(item.metadata as Record<string, unknown> | undefined)?.screenRecording === true && (
                    <span className="shrink-0 rounded border border-[#8505D5]/40 bg-[#8505D5]/10 px-1.5 py-0.5 text-[10px] text-[#d9b3ff]">screen recording</span>
                  )}
                  <span className="shrink-0 text-[10px] text-white/40">{item.status}</span>
                </button>
              ))}
            </div>
          )}
          <p className="text-[10px] text-white/40">Every storyboard shot will be cut from the recording you pick — no Veo spend is made for any of them. Leave it off and each shot is generated by Veo.</p>
        </DialogContent>
      </Dialog>

      <div>
        <button onClick={onOpenChat} className="text-xs text-white/50 underline hover:text-white">Discuss this project with the assistant</button>
      </div>
    </div>
  );
}
