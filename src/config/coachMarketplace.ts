// ============================================================================
// COACH MARKETPLACE — pricing and commission, one source of truth
// ----------------------------------------------------------------------------
// A coach sets the price THEY want to be paid. The buyer pays that price plus
// the platform's commission on top. The coach always receives exactly what they
// asked for, and the difference between the two numbers is what Vaylo keeps.
//
//   coach asks        £5.00   500 minor units   <- netCents
//   commission @ 20%  £1.00                      <- feeCents
//   buyer is charged  £6.00   600 minor units   <- grossCents
//
// That ordering is the whole design, and it is not cosmetic. Charging the buyer
// the coach's price and then taking a cut would mean a coach who asks for £5
// receives £4 — a number they never chose and cannot predict, which is exactly
// the promise this file exists to keep. Expressing commission as a *markup on
// the coach's price* is also what lets the marketing sentence be true: "you
// receive what you ask for".
//
// The percentage is bounded. COACH_COMMISSION_MIN_PERCENT..MAX_PERCENT is the
// band the product is willing to run at, and quoteCoachPrice() refuses to
// compute anything outside it rather than quietly charging a number nobody
// agreed to. The database holds the same bound (`marketplace_check_commission`)
// and is the authority for what is actually charged.
//
// WHO ENFORCES WHAT
//
//   this file         display: the coach's own price preview, the "you receive
//                     / buyer pays" split on a listing, the fee on the signup
//                     page. Also the mirror the edge functions compute with.
//   the database      the charge. `public.marketplace_quote(net_cents)` reads
//                     marketplace_config and is what the checkout paths call,
//                     for the same reason feature prices come from
//                     `public.credit_cost()` rather than a constant.
//
// The two cannot drift by a typo: `npm run gen:coach` copies this file verbatim
// into supabase/functions/_shared/coachMarketplace.ts, and a test fails if the
// committed copy is stale. Nothing here imports anything, on purpose — that is
// what makes the verbatim copy safe in a Deno edge runtime.
// ============================================================================

/**
 * The platform's commission, as a percentage added on top of the coach's price.
 *
 * 20% of a £5 plan is £1, so the buyer pays £6 — the worked example this
 * product was specified with. The rate is a single number rather than a
 * scattered set of constants so that changing it is one edit in one file, one
 * `npm run gen:coach`, one migration value, and the tests below say whether the
 * result is still inside the band.
 */
export const COACH_COMMISSION_PERCENT = 20;

/** The band the product is willing to operate in. Outside it, nothing is quoted. */
export const COACH_COMMISSION_MIN_PERCENT = 10;
export const COACH_COMMISSION_MAX_PERCENT = 20;

/**
 * What a coach pays once, on the website, to become a coach.
 *
 * $20, charged through Stripe on the website only. Deliberately NOT charged in
 * the app: a "become a coach" purchase is a digital good, so Play's rules would
 * require it to go through Play Billing, and the fee buys access to sell rather
 * than a consumable — the website is where this belongs and is also where a
 * person can enter business details they would not type on a phone.
 */
export const COACH_SIGNUP_FEE_CENTS = 2000;
export const COACH_SIGNUP_FEE_CURRENCY = "USD";

/**
 * Plan prices are set in GBP pence.
 *
 * One currency, on purpose. Converting a coach's own price into a buyer's local
 * currency would mean the coach is paid a number they did not choose whenever a
 * rate moved, which is the one thing the split exists to prevent. A coach prices
 * in pounds and is paid in pounds.
 */
export const COACH_PLAN_CURRENCY = "GBP";

/**
 * Plan price bounds, in minor units.
 *
 * The floor exists because commission on a very small price rounds to nothing:
 * below £1 the platform would be giving away the payment-processing cost. The
 * ceiling matches `guard_listing_insert()` in the database, which already
 * refuses a listing outside 0..100000000.
 */
export const COACH_MIN_PLAN_CENTS = 100;
export const COACH_MAX_PLAN_CENTS = 100000000;

/** Where a person goes to create a coach account. Generated by the website build. */
export const COACH_SIGNUP_PATH = "/coaches/";

/**
 * The fixed-value top-up products a buyer buys with Google Play Billing.
 *
 * Play cannot charge a price your server chooses at runtime: a one-time product
 * has to exist in the Play Console with a price attached, before anybody tries
 * to buy it. A coach's price is different for every coach, so it cannot be a
 * Play product.
 *
 * The way through is a wallet. The buyer tops up coaching credits in fixed
 * amounts through Play — which is a normal, rule-compliant purchase of a
 * consumable — and then spends that balance on a listing, at the listing's own
 * price, server-side. One credit is one penny, so a £5 top-up and a £5.00 plan
 * are the same number of credits, and the coin/credit economy is untouched: a
 * coaching credit is not a Vaylo credit and cannot buy AI features.
 *
 * The ids here must exist in the Play Console with matching prices before the
 * marketplace is switched on. See docs/COACH-MARKETPLACE.md §4.
 */
export const COACH_CREDIT_PACKS = [
  { id: "coach_credits_5", price_cents: 500, credit_cents: 500, currency: "GBP" },
  { id: "coach_credits_10", price_cents: 1000, credit_cents: 1000, currency: "GBP" },
  { id: "coach_credits_25", price_cents: 2500, credit_cents: 2500, currency: "GBP" },
] as const;

/** Percent → basis points, rounded to the nearest basis point. */
export const commissionPercentToBps = (percent: number): number => Math.round(percent * 100);

/** True when a commission rate is one this product is willing to charge. */
export const commissionIsInBand = (percent: number): boolean =>
  Number.isFinite(percent) &&
  percent >= COACH_COMMISSION_MIN_PERCENT &&
  percent <= COACH_COMMISSION_MAX_PERCENT;

export interface CoachPriceQuote {
  /** What the coach asked for and will be paid. */
  netCents: number;
  /** Vaylo's commission — the difference between the two other numbers. */
  feeCents: number;
  /** What the buyer is charged. */
  grossCents: number;
  commissionBps: number;
}

/**
 * The split, for a coach's asking price.
 *
 * Integer arithmetic throughout: money is minor units, never a float, because
 * 0.2 × 500 is 100.00000000000001 in binary floating point and a platform that
 * charges £6.0000000001 has a bug you only find in a reconciliation.
 *
 * Throws rather than returning a partial quote when the input is impossible, so
 * there is no path where a caller gets a gross price for a rate the product does
 * not offer. Callers that want to validate first use `coachPlanError()`.
 */
export function quoteCoachPrice(
  netCents: number,
  commissionPercent: number = COACH_COMMISSION_PERCENT,
): CoachPriceQuote {
  if (!Number.isInteger(netCents) || netCents <= 0) {
    throw new Error(`coach price must be a positive whole number of minor units, got ${netCents}`);
  }
  if (!commissionIsInBand(commissionPercent)) {
    throw new Error(
      `coach commission ${commissionPercent}% is outside the ${COACH_COMMISSION_MIN_PERCENT}–${COACH_COMMISSION_MAX_PERCENT}% band`,
    );
  }
  const commissionBps = commissionPercentToBps(commissionPercent);
  const feeCents = Math.round((netCents * commissionBps) / 10000);
  return { netCents, feeCents, grossCents: netCents + feeCents, commissionBps };
}

/**
 * Why a plan price is not acceptable, or null when it is.
 *
 * A string rather than a boolean because every rejection here is shown to a
 * coach typing a price, and "invalid price" tells them nothing.
 */
export function coachPlanError(netCents: number): string | null {
  if (!Number.isFinite(netCents) || !Number.isInteger(netCents)) {
    return "Enter a price in whole pence.";
  }
  if (netCents < COACH_MIN_PLAN_CENTS) {
    return `The lowest plan price is ${formatMinorUnits(COACH_MIN_PLAN_CENTS, COACH_PLAN_CURRENCY)}.`;
  }
  if (netCents > COACH_MAX_PLAN_CENTS) {
    return "That price is higher than the marketplace allows.";
  }
  return null;
}

/**
 * Money for display, from minor units.
 *
 * Intl rather than the app's `formatLocalPrice()`, which converts a price by a
 * regional rate table. A coach's price is not a converted USD price — it is the
 * coach's own number in the currency they set it in — and running it through a
 * rate table would show a coach a price they never typed.
 */
export function formatMinorUnits(cents: number, currency: string): string {
  const amount = cents / 100;
  try {
    return new Intl.NumberFormat("en-GB", {
      style: "currency",
      currency,
      minimumFractionDigits: 2,
      maximumFractionDigits: 2,
    }).format(amount);
  } catch {
    // An unknown currency code must not throw on a screen that is merely
    // showing a price. Fall back to the code and the number.
    return `${currency} ${amount.toFixed(2)}`;
  }
}

/**
 * A stable, tiny key for a quote, used in tests and log lines.
 *
 * Not money — nothing is decided from it. It exists so a failing checkout can
 * print the exact split it was refusing.
 */
export const describeQuote = (quote: CoachPriceQuote): string =>
  `${quote.netCents}/${quote.feeCents}/${quote.grossCents}@${quote.commissionBps}bps`;
