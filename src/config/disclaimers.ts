// Each entry is the shortest text that is actually true. No blanket
// "we accept no liability" clauses: those are unenforceable against a consumer
// in the UK (Consumer Rights Act 2015 s.3, Consumer Contracts Regulations 2013
// s.65(2)) and their presence makes the honest disclaimers next to them read as
// boilerplate too.
//
// What each one is for:
//
//   healthRisk      — the app gives training loads and intensity targets. Getting
//                     those wrong, or training through illness, causes injury.
//   aiEstimate      — every AI output is a model estimate, not a measurement.
//   nutrition       — calorie/macro figures are estimates and are not dietetic
//                     advice; this is separate from healthRisk because the
//                     failure mode (an eating disorder) is different.
//   minor           — the app is built for adult athletes, and an under-18
//                     athlete must not follow adult loading; diet plans are not
//                     offered to them at all.
//   formAnalysis    — a photo/video analysis is not a physio or clinician.
//   closedTesting   — credits are free right now and that will change.
//   billing         — once billing is live, purchases are final in the way the
//                     store says they are; we do not set store refund policy.
//
// Version string: bump it whenever the text changes so a stored acceptance
// (profiles.terms_version) can be told apart from a later wording.
// ============================================================================

